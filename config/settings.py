# Enable SQLite WAL (Write-Ahead Logging) mode on every new connection.
# WAL allows concurrent readers + one writer instead of a full file-lock,
# which is critical when background benchmark threads write results while
# the web server is serving HTTP requests.
from django.db.backends.signals import connection_created  # noqa: E402

def _enable_wal(sender, connection, **kwargs):
    if connection.vendor == 'sqlite':
        with connection.cursor() as cursor:
            cursor.execute('PRAGMA journal_mode=WAL;')
            cursor.execute('PRAGMA synchronous=NORMAL;')

connection_created.connect(_enable_wal)

